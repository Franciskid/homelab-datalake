"""Keycloak sign-ins: every login, logout, token exchange and failure across every SSO app.

Read from Keycloak's own Postgres database with the `datalake_ro` role, which is granted
SELECT on exactly the columns named here -- see infra/keycloak-datalake-grants.sql,
which `render_grant_sql()` generates and a test holds in step. Client secrets and
registration tokens are never granted, so they cannot be read even by mistake.

Nothing lands until events are switched on: on 2026-09-15 both realms had
`events_enabled = false` and `event_entity` was empty. scripts/setup-keycloak-events.sh
turns them on with a 90-day expiry; the lake keeps them after Keycloak expires them.

Events are immutable, so a day's partition is merged by event id and never shrinks --
re-reading a day Keycloak has already expired keeps what the lake landed. Users,
clients and realms are ledgers (parsing/ledger.py), so a renamed or deleted account
keeps the name its old events were signed in under.
"""

import os
from datetime import UTC, date, datetime, time, timedelta

import pyarrow as pa
from dagster import (
    AssetCheckResult,
    AssetCheckSpec,
    AssetExecutionContext,
    DailyPartitionsDefinition,
    DefaultScheduleStatus,
    MaterializeResult,
    RetryPolicy,
    RunRequest,
    ScheduleEvaluationContext,
    asset,
    define_asset_job,
    schedule,
)

from homelab_datalake import lakeio, layout
from homelab_datalake.parsing import ledger
from homelab_datalake.resources import LakeStorage

KEYCLOAK_EVENTS_START = "2026-09-15"
# end_offset=1: the schedule re-reads today every hour, and without it today is not a
# partition until midnight, so every tick fails on an unknown key.
keycloak_partitions = DailyPartitionsDefinition(start_date=KEYCLOAK_EVENTS_START, timezone="UTC", end_offset=1)

EVENT_COLUMNS = ("id", "event_time", "type", "realm_id", "client_id", "user_id", "session_id",
                 "ip_address", "error", "details_json", "details_json_long_value")
ADMIN_EVENT_COLUMNS = ("id", "admin_event_time", "realm_id", "operation_type", "resource_type",
                       "resource_path", "auth_realm_id", "auth_client_id", "auth_user_id",
                       "ip_address", "error", "representation", "details_json")
USER_COLUMNS = ("id", "realm_id", "username", "email", "email_verified", "first_name", "last_name",
                "enabled", "created_timestamp", "last_modified_timestamp", "federation_link",
                "service_account_client_link", "not_before")
# Not `secret`, not `registration_token`.
CLIENT_COLUMNS = ("id", "realm_id", "client_id", "name", "description", "enabled", "protocol",
                  "public_client", "bearer_only", "service_accounts_enabled", "standard_flow_enabled",
                  "implicit_flow_enabled", "direct_access_grants_enabled", "client_authenticator_type",
                  "root_url", "base_url", "created_timestamp", "last_modified_timestamp")
REALM_COLUMNS = ("id", "name", "enabled", "events_enabled", "events_expiration",
                 "admin_events_enabled", "admin_events_details_enabled")

GRANTED = {
    "event_entity": EVENT_COLUMNS,
    "admin_event_entity": ADMIN_EVENT_COLUMNS,
    "user_entity": USER_COLUMNS,
    "client": CLIENT_COLUMNS,
    "realm": REALM_COLUMNS,
}
LEDGERS = {"keycloak_users": "user_entity", "keycloak_clients": "client", "keycloak_realms": "realm"}

EVENTS_PREFIX = layout.prefix("keycloak_events")
ADMIN_EVENTS_PREFIX = layout.prefix("keycloak_admin_events")

EVENT_SCHEMA = pa.schema([
    ("dt", pa.date32()), ("event_at", pa.timestamp("ms", tz="UTC")),
    *[(c, pa.int64() if c == "event_time" else pa.string()) for c in EVENT_COLUMNS],
])
ADMIN_EVENT_SCHEMA = pa.schema([
    ("dt", pa.date32()), ("event_at", pa.timestamp("ms", tz="UTC")),
    *[(c, pa.int64() if c == "admin_event_time" else pa.string()) for c in ADMIN_EVENT_COLUMNS],
])

CHECK_NOT_SHRUNK = "partition_did_not_shrink"


def render_grant_sql() -> str:
    lines = [
        "-- GENERATED by homelab_datalake.assets.keycloak.render_grant_sql(). Do not hand-edit;",
        "-- tests/test_sources_added_2026_09_15.py fails when this file and the code disagree.",
        "--",
        "-- Lets the existing read-only role `datalake_ro` read Keycloak's sign-in events and the",
        "-- names they point at -- and nothing else. Column-level, so `client.secret` and",
        "-- `client.registration_token` cannot be selected even by mistake.",
        "-- Run once on the Keycloak database as a superuser:",
        "--   docker exec -i postgresql_postgres_1 psql -U postgres -d keycloak < infra/keycloak-datalake-grants.sql",
        "",
        "GRANT CONNECT ON DATABASE keycloak TO datalake_ro;",
        "GRANT USAGE ON SCHEMA public TO datalake_ro;",
    ]
    for table, columns in GRANTED.items():
        lines.append(f"GRANT SELECT ({', '.join(columns)}) ON public.{table} TO datalake_ro;")
    return "\n".join(lines) + "\n"


def connection_settings() -> dict:
    """The same `datalake_ro` role the LiteLLM source uses, on the keycloak database.

    The KEYCLOAK_PG_* variables exist so the two can be split later; unset, each one
    falls back to its LITELLM_PG_* counterpart rather than asking for the same
    password to be copied into a second variable.
    """
    def setting(name: str, default: str = "") -> str:
        return os.environ.get(f"KEYCLOAK_PG_{name}") or os.environ.get(f"LITELLM_PG_{name}", default)

    return {
        "host": setting("HOST", "localhost"),
        "port": int(setting("PORT", "5432")),
        "dbname": os.environ.get("KEYCLOAK_PG_DB", "keycloak"),
        "user": setting("USER"),
        "password": setting("PASSWORD"),
    }


def _query(cursor, table: str, columns: tuple[str, ...], where: str = "", params=None) -> list[dict]:
    cursor.execute(f"SELECT {', '.join(columns)} FROM public.{table} {where}", params)  # noqa: S608
    return [dict(zip(columns, record, strict=True)) for record in cursor.fetchall()]


def event_rows(records: list[dict], time_column: str) -> list[dict]:
    rows = []
    for record in records:
        millis = record.get(time_column)
        if millis is None:
            continue
        at = datetime.fromtimestamp(millis / 1000, UTC)
        rows.append({"dt": at.date(), "event_at": at,
                     **{k: (v if k == time_column else ledger.as_text(v)) for k, v in record.items()}})
    return rows


def merge_events(lake: LakeStorage, key: str, rows: list[dict], schema: pa.Schema) -> tuple[int, int]:
    """Union by id. Returns (rows before, rows after)."""
    existing = lakeio.read_strict(lake, key)
    merged = {row["id"]: row for row in (existing.to_pylist() if existing is not None else [])}
    before = len(merged)
    for row in rows:
        merged[row["id"]] = row
    if len(merged) != before or rows:
        ordered = sorted(merged.values(), key=lambda r: (r["event_at"], r["id"]))
        lake.write_table(key, pa.Table.from_pylist(ordered, schema=schema))
    return before, len(merged)


@asset(
    partitions_def=keycloak_partitions,
    group_name="keycloak",
    kinds={"python", "postgres"},
    retry_policy=RetryPolicy(max_retries=3, delay=30),
    check_specs=[AssetCheckSpec(
        name=CHECK_NOT_SHRUNK, asset="keycloak_raw",
        description="A day's events are merged by id and never lose a row Keycloak has since expired.",
    )],
    description=(
        "One UTC day of Keycloak user events (logins, logouts, token exchanges, errors) and "
        "admin events, plus ledgers of the users, clients and realms they refer to."
    ),
)
def keycloak_raw(context: AssetExecutionContext, lake: LakeStorage) -> MaterializeResult:
    import psycopg

    day = date.fromisoformat(context.partition_key)
    start = datetime.combine(day, time.min, tzinfo=UTC)
    bounds = {"start": int(start.timestamp() * 1000), "end": int((start + timedelta(days=1)).timestamp() * 1000)}
    captured_at = datetime.now(UTC)
    with psycopg.connect(**connection_settings()) as connection, connection.cursor() as cursor:
        events = _query(cursor, "event_entity", EVENT_COLUMNS,
                        "WHERE event_time >= %(start)s AND event_time < %(end)s", bounds)
        admin = _query(cursor, "admin_event_entity", ADMIN_EVENT_COLUMNS,
                       "WHERE admin_event_time >= %(start)s AND admin_event_time < %(end)s", bounds)
        lookups = {name: _query(cursor, table, GRANTED[table]) for name, table in LEDGERS.items()}

    events_before, events_after = merge_events(
        lake, f"{EVENTS_PREFIX}/dt={day.isoformat()}/data.parquet", event_rows(events, "event_time"), EVENT_SCHEMA)
    admin_before, admin_after = merge_events(
        lake, f"{ADMIN_EVENTS_PREFIX}/dt={day.isoformat()}/data.parquet",
        event_rows(admin, "admin_event_time"), ADMIN_EVENT_SCHEMA)
    ledger_stats = {}
    for name, rows in lookups.items():
        key = f"{layout.prefix(name)}/data.parquet"
        table, stats = ledger.merge(lakeio.read_strict(lake, key), rows, ("id",), captured_at)
        lake.write_table(key, table)
        ledger_stats[name] = stats.versions_after

    types: dict[str, int] = {}
    for event in events:
        types[event["type"]] = types.get(event["type"], 0) + 1
    context.log.info("%s events=%d admin=%d types=%s ledgers=%s", day, len(events), len(admin), types, ledger_stats)
    return MaterializeResult(
        metadata={"events": events_after, "admin_events": admin_after,
                  "events_read": len(events), "by_type": types, **{f"{k}_versions": v for k, v in ledger_stats.items()}},
        check_results=[AssetCheckResult(
            check_name=CHECK_NOT_SHRUNK, passed=events_after >= events_before and admin_after >= admin_before,
            metadata={"events_before": events_before, "events_after": events_after},
        )],
    )


keycloak_job = define_asset_job(
    name="keycloak", selection=[keycloak_raw],
    description="Land one day of Keycloak sign-in and admin events.",
)


@schedule(job=keycloak_job, cron_schedule="35 * * * *",
          default_status=DefaultScheduleStatus.STOPPED,
          description=(
              "Today and yesterday, hourly. Merged by id, so re-reading a day is free, and a "
              "sign-in is in the lake within the hour."
          ))
def keycloak_schedule(context: ScheduleEvaluationContext):
    today = context.scheduled_execution_time.date()
    stamp = f"{context.scheduled_execution_time:%Y%m%d%H}"
    for back in (0, 1):
        day = today - timedelta(days=back)
        if day.isoformat() >= KEYCLOAK_EVENTS_START:
            yield RunRequest(run_key=f"keycloak-{day.isoformat()}-{stamp}", partition_key=day.isoformat())


ASSETS = [keycloak_raw]
JOBS = [keycloak_job]
SCHEDULES = [keycloak_schedule]
