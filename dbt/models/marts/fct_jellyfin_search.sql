-- One row per search request logged by the AI Search plugin: what was searched,
-- by whom, through which endpoint, and whether the semantic layer ran.
--
-- No join to dim_jellyfin_user, unlike fct_jellyfin_activity: the plugin logs
-- user_name on the request itself, the same reasoning fct_jellyfin_playback's own
-- user_name carries straight through from the raw row rather than through a join.

select
    search_id                                          as search_key,
    partition_date,
    partition_hour,
    extracted_at,
    searched_at,
    date_trunc('hour', searched_at)                    as searched_hour,
    extract('hour' from searched_at)                   as searched_hour_of_day,
    dayname(searched_at)                                as searched_weekday,
    (dayofweek(searched_at) in (0, 6))                  as is_weekend,
    kind,
    is_ai_search,
    endpoint,
    method,
    status_code,
    duration_ms,
    search_term,
    user_id,
    user_name,
    is_api_key,
    client,
    client_version,
    device,
    device_id,
    remote_address,
    client_hash,
    client_network,
    client_trust,
    user_agent,
    parameters_json,
    parent_id,
    parent_name,
    result_count,
    total_record_count,
    results_logged,
    had_no_results,
    semantic_enabled,
    semantic_ran,
    semantic_skipped_reason,
    semantic_mode,
    semantic_duration_ms,
    semantic_raw_hits,
    semantic_matches,
    semantic_error,
    mode,
    answer,
    unmapped_json
from {{ ref('stg_jellyfin_searches') }}
